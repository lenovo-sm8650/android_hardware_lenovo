# Generates the lenovo_strings.xml of the Settings fork (packages/apps/Settings/res), the
# Battery page controls and the white balance strength.
# The text of every locale is in settings_strings.json ("en" is the default; a locale only lists the
# strings that differ from English, the others fall back to it). Locales are the
# values-* set of the AOSP Settings app. Translations come from the stock ZUI Settings
# and AOSP strings where an equivalent exists, the rest was written for these apps; edit
# the JSON and run this script to regenerate the XML.
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = json.load(open(os.path.join(HERE, 'settings_strings.json')))
TARGETS = [('settings', '../../../packages/apps/Settings/res', 'lenovo_strings.xml')]


def esc(s):
    s = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    s = s.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    if s.startswith('@') or s.startswith('?'):
        s = '\\' + s
    return s


def attrs(s):
    # a literal % without positional args would be taken as a format string
    literal = re.sub(r'%\d\$[sd]', '', s)
    return ' formatted="false"' if '%' in literal else ''


HEADER = '''<?xml version="1.0" encoding="utf-8"?>
<!--
     SPDX-FileCopyrightText: 2026 The LineageOS Project
     SPDX-License-Identifier: Apache-2.0
-->
<!-- Generated by tools/settings_strings.py from settings_strings.json; edit the JSON. -->
<resources>
'''

for app, res_dir, filename in TARGETS:
    table = DATA[app]
    en = table['en']
    for lang, strings in table.items():
        out = [HEADER]
        for key, value in en.items():
            v = strings.get(key)
            if v is None:
                continue
            if isinstance(value, list):
                out.append(f'    <string-array name="{key}">\n')
                for item in v:
                    out.append(f'        <item>{esc(item)}</item>\n')
                out.append('    </string-array>\n')
            else:
                out.append(f'    <string name="{key}"{attrs(v)}>{esc(v)}</string>\n')
        out.append('</resources>\n')
        d = os.path.join(HERE, res_dir, 'values' if lang == 'en' else 'values-' + lang)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, filename), 'w') as f:
            f.write(''.join(out))
    print(app, len(table), 'locales')
